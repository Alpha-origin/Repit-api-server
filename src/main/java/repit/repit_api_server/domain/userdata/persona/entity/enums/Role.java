package repit.repit_api_server.domain.userdata.persona.entity.enums;

/**
 * 면접관의 직책. 말투(type)와는 독립된 축이다.
 *
 * <p>1:1 면접은 기술 면접관 한 명뿐이라 전부 {@link #TECH}다. N:1 면접은 기술 한 명에
 * 다른 직책이 한 명씩 더 붙는다. 직책은 질문 관점과 채점 관점에 반영된다 — 기술은 근거와
 * 트레이드오프, 인사는 동기의 구체성, CEO는 우선순위 판단.
 *
 * <p>표기는 영문 대문자 상수로 고정한다. 분석 서버는 대소문자를 무시하고 이 이름으로 직책별
 * 질문 관점을 찾으며, 모르는 값이 와도 기본 지침으로 폴백하고 422로 깨지지는 않는다.
 * 그래도 한쪽 표기만 남겨야 값이 어디서 정해지는지가 한 곳으로 모인다.
 */
public enum Role {
    TECH,
    HR,
    CEO,
    PM,
    DESIGN
}
